alter table public.cvs enable row level security;
alter table public.drama_cvs enable row level security;
alter table public.sync_log enable row level security;
alter table public.user_missevan_credentials enable row level security;
alter table public.sync_jobs enable row level security;
alter table public.migration_state enable row level security;

create policy "profiles_self" on public.profiles
  for select to authenticated using ((select auth.uid()) = id);
create policy "profiles_update_self" on public.profiles
  for update to authenticated using ((select auth.uid()) = id)
  with check ((select auth.uid()) = id);

create policy "dramas_self" on public.dramas
  for all to authenticated using ((select auth.uid()) = user_id)
  with check ((select auth.uid()) = user_id);
create policy "cvs_self" on public.cvs
  for all to authenticated using ((select auth.uid()) = user_id)
  with check ((select auth.uid()) = user_id);
create policy "drama_cvs_self" on public.drama_cvs
  for all to authenticated
  using (exists (select 1 from public.dramas d where d.id = drama_id and d.user_id = (select auth.uid())))
  with check (exists (select 1 from public.dramas d where d.id = drama_id and d.user_id = (select auth.uid())));
create policy "sync_log_self" on public.sync_log
  for select to authenticated using ((select auth.uid()) = user_id);
create policy "sync_jobs_self" on public.sync_jobs
  for select to authenticated using ((select auth.uid()) = user_id);
create policy "migration_state_self" on public.migration_state
  for select to authenticated using ((select auth.uid()) = user_id);

-- user_missevan_credentials 没有客户端策略，只有服务端 service role 可访问。

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer set search_path = ''
as $$
begin
  insert into public.profiles (id, display_name)
  values (new.id, coalesce(new.raw_user_meta_data ->> 'display_name', split_part(new.email, '@', 1)));
  return new;
end;
$$;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute procedure public.handle_new_user();

